from typing import Annotated

from fastapi import (
    APIRouter,
    Body,
    Depends,
    HTTPException,
    status,
)
from sqlalchemy.orm import Session

from app.api.dependencies import get_airport_catalog
from app.db.repositories.route_catalog_repository import (
    RouteCatalogRepository,
)
from app.db.session import get_db
from app.engines.route_engine import RouteEngine
from app.providers.airport_catalog import AirportCatalog
from app.schemas.route import (
    RouteRecommendationRequest,
    RouteRecommendationResponse,
)


router = APIRouter(
    prefix="/routes",
    tags=["Route Engine"],
)


# ============================================================
# Route Recommendations
# ============================================================


@router.post(
    "/recommend",
    response_model=RouteRecommendationResponse,
    status_code=status.HTTP_200_OK,
    summary="Generate Route Recommendations",
    description=(
        "Generates flight route recommendations using "
        "the Route Engine.\n\n"
        "The engine processes the supplied route selection "
        "criteria and uses the Route Catalog and Airport "
        "Catalog to identify suitable flight routes.\n\n"
        "**Recommendation process:**\n"
        "1. Accepts the route recommendation parameters.\n"
        "2. Initialises the Route Engine with the route "
        "repository and airport catalog.\n"
        "3. Evaluates available routes against the supplied "
        "selection criteria.\n"
        "4. Returns the recommendation results generated "
        "by the Route Engine.\n\n"
        "**Route selection:**\n\n"
        "The available selection criteria are defined by "
        "the `RouteRecommendationRequest` schema. These "
        "may include departure and destination airports, "
        "flight duration restrictions, aircraft preferences, "
        "and additional route filters.\n\n"
        "**Data sources:**\n"
        "- **Route Catalog:** Provides route records "
        "through the database repository.\n"
        "- **Airport Catalog:** Provides airport information "
        "used during route evaluation.\n\n"
        "**Error handling:**\n"
        "- **404 Not Found:** A required resource "
        "could not be located.\n"
        "- **422 Unprocessable Entity:** Invalid request "
        "parameters or an evaluation constraint prevented "
        "route recommendation generation.\n\n"
        "**Note:** This endpoint generates recommendations "
        "without modifying stored route records."
    ),
    response_description=(
        "Route recommendation results generated by the "
        "Route Engine, structured according to the "
        "RouteRecommendationResponse schema."
    ),
    responses={
        404: {
            "description": (
                "A required airport, aircraft, route, or "
                "other resource could not be found."
            ),
            "content": {
                "application/json": {
                    "example": {
                        "detail": "Requested resource not found."
                    },
                },
            },
        },
        422: {
            "description": (
                "Request validation failed or the Route "
                "Engine rejected the supplied parameters."
            ),
        },
    },
)
def recommend_routes(
    request: Annotated[
        RouteRecommendationRequest,
        Body(
            description=(
                "Route recommendation parameters defining "
                "the desired flight characteristics, "
                "aircraft preferences, airport filters, "
                "and additional selection criteria."
            ),
        ),
    ],
    catalog: Annotated[
        AirportCatalog,
        Depends(get_airport_catalog),
    ],
    db: Annotated[
        Session,
        Depends(get_db),
    ],
) -> RouteRecommendationResponse:
    """
    Generate flight route recommendations.

    Initialises the Route Engine using the route catalog
    repository and airport catalog, then evaluates the
    supplied recommendation criteria.

    The engine is responsible for generating and selecting
    suitable routes according to its configured logic.

    Args:
        request:
            Route recommendation parameters containing
            the selection criteria and preferences.

        catalog:
            Airport catalog dependency used to access
            airport information during route evaluation.

        db:
            Database session provided by FastAPI.

    Returns:
        RouteRecommendationResponse:
            Route recommendations and associated
            response information generated by the engine.

    Raises:
        HTTPException:
            404 if a required resource cannot be found.

            422 if the recommendation parameters are
            invalid or the engine raises a ValueError.
    """
    engine = RouteEngine(
        repository=RouteCatalogRepository(db),
        airport_catalog=catalog,
    )

    try:
        return engine.recommend(request)

    except LookupError as exc:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=str(exc),
        ) from exc

    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=str(exc),
        ) from exc