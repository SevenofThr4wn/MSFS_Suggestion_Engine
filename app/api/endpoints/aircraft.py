from typing import Annotated

from fastapi import (
    APIRouter,
    Body,
    Depends,
    HTTPException,
    Path,
    status,
)
from sqlalchemy.orm import Session

from app.db.session import get_db
from app.db.repositories.aircraft_repository import (
    AircraftRepository,
)
from app.engines.aircraft_engine import AircraftEngine
from app.schemas.aircraft import (
    AircraftDetailResponse,
    AircraftEvaluationRequest,
    AircraftRecommendationResponse,
)


router = APIRouter(
    prefix="/aircraft",
    tags=["Aircraft Engine"],
)


@router.post(
    "/evaluate",
    response_model=AircraftRecommendationResponse,
    status_code=status.HTTP_200_OK,
    summary="Evaluate Aircraft",
    description=(
        "Evaluates aircraft suitability using the Aircraft Engine.\n\n"
        "The engine processes the supplied evaluation criteria "
        "and uses aircraft data stored in the database to "
        "generate a recommendation.\n\n"
        "**Evaluation process:**\n"
        "1. Accepts the aircraft evaluation parameters.\n"
        "2. Retrieves relevant aircraft data from the database.\n"
        "3. Executes the Aircraft Engine's evaluation logic.\n"
        "4. Returns the resulting aircraft recommendation.\n\n"
        "**Note:** The evaluation does not modify aircraft "
        "records stored in the database."
    ),
    response_description=(
        "The aircraft evaluation results and recommendation "
        "generated by the Aircraft Engine."
    ),
    responses={
        422: {
            "description": (
                "Validation error: One or more supplied evaluation "
                "parameters are invalid."
            )
        }
    }
)
def evaluate_aircraft(
    request: Annotated[
        AircraftEvaluationRequest,
        Body(
            description=(
                "Parameters used by the Aircraft Engine to "
                "evaluate and recommend aircraft"
            )
        )
    ],
    db: Session = Depends(get_db),
):
    """
    Evaluate aircraft using the supplied criteria.

    Retrieves aircraft information through the repository
    and delegates suitability evaluation to the Aircraft Engine.

    Args:
        request: Aircraft evaluation parameters.
        db: Database session provided by FastAPI.

    Returns:
        AircraftRecommendationResponse:
            The aircraft recommendation generated by the engine.
    """

    repository = AircraftRepository(db)
    engine = AircraftEngine(repository)

    return engine.recommend(request)


@router.get(
    "/{aircraft_id}",
    response_model=AircraftDetailResponse,
    status_code=status.HTTP_200_OK,
    summary="Get Aircraft Details",
    description=(
        "Retrieves detailed information about a specific aircraft "
        "stored in the aircraft database.\n\n"
        "The aircraft is identified using its unique database ID.\n\n"
        "**Returned information includes:**\n"
        "- Aircraft name and ICAO type designator.\n"
        "- Aircraft category.\n"
        "- Maximum range in nautical miles.\n"
        "- Cruise speed in knots.\n"
        "- Takeoff and landing distance requirements in metres.\n"
        "- Whether the aircraft is owned by the user.\n\n"
        "Returns **404 Not Found** if no aircraft exists "
        "with the specified ID."
    ),
    response_description=(
        "Detailed information about the requested aircraft."
    ),
    responses={
        404: {
            "description": (
                "No aircraft exists with the specified ID."
            ),
            "content": {
                "application/json": {
                    "example": {
                        "detail": "Aircraft not found"
                    },
                },
            },
        },
        422: {
            "description": (
                "Invalid aircraft ID. The ID must be "
                "a positive integer."
            ),
        },
    },
)
def get_aircraft(
    aircraft_id: Annotated[
        int,
        Path(
            title="Aircraft ID",
            description=(
                "Unique database identifier of the aircraft "
                "to retrieve."
            ),
            ge=1,
            examples=[1],
        ),
    ],
    db: Session = Depends(get_db),
):
    """
    Retrieve an aircraft by its unique database ID.

    Args:
        aircraft_id: Unique identifier of the aircraft.
        db: Database session provided by FastAPI.

    Returns:
        AircraftDetailResponse:
            Detailed information about the requested aircraft.

    Raises:
        HTTPException:
            404 if the aircraft does not exist.
    """
    
    repository = AircraftRepository(db)

    aircraft = repository.get_by_id(aircraft_id)

    if aircraft is None:
        raise HTTPException(
            status_code=404,
            detail="Aircraft not found",
        )

    return {
        "id": aircraft.id,
        "name": aircraft.display_name,
        "icao_code": aircraft.icao_code,
        "category": aircraft.category,
        "range_nm": aircraft.range_nm,
        "cruise_speed_kts": aircraft.cruise_speed_kts,
        "takeoff_distance_m": aircraft.takeoff_distance_m,
        "landing_distance_m": aircraft.landing_distance_m,
        "is_owned": aircraft.is_owned,
    }
